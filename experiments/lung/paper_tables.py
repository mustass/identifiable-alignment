#!/usr/bin/env python
"""Build the paper's scVI-lung tables and figure from the two readouts.

Inputs (both under --root):
  results/lung_table.csv          read_fits.py: NGMA (M = 1, 8, euc), ceilings, per fit
  baselines/lung_baselines.csv    read_baselines.py: the baselines a -> b, per carve
All numbers are disjoint carves (n = 3,000 per side), mean +- s.d. over the 2 pairs x 3 draws of a
row. Writes to --out:

  tab_lung_baselines.tex   R@1 and cell-type accuracy: NGMA (M = 8), NGMA with Euclidean
                           geometry, Rosetta, mini-vec2vec, GENOT-Q (both costs), RelGeo, and the
                           two maps fitted on the true pairs
  tab_lung_resolution.tex  NGMA's combined ranking for M = 1, M = 8 and Euclidean; at M = 8 R@1
                           within cell type (with chance), cell-type and compartment accuracy
  tab_lung_draws.tex       every carve, R@1 of every method (appendix)
  lung_numbers.json        the numbers the text quotes
  fig_lung_main.pdf        1 x 2: R@1 and cell-type accuracy against training size, models
                           trained on different cells, every draw shown (+ .png, + .tex)

NGMA is scored by the combined ranking of both maps (the unsuffixed columns of lung_table.csv).
The baselines' a -> b numbers equal their combined ranking (an orthogonal map's inverse is its
transpose, and RelGeo's relative distances are symmetric); GENOT-Q is a -> b. The two ceilings
are scored a -> b: fit_map.py trains the oracle for that direction.

    python experiments/lung/paper_tables.py --root <root> --out <dir>
"""
import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

SIZES = (4900, 9800, 19600)
KINDS = (("cross", "different cells"), ("within", "same cells"))
PAIR_NO = {"cross1": 1, "cross2": 2, "within1": 3, "within2": 4}   # the paper's pair numbers
HEADER = "% Generated by experiments/lung/paper_tables.py from {src}. Do not edit by hand; rebuild.\n"


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def ms(vals, d=3):
    v = [x for x in vals if x is not None]
    if not v:
        return "--"
    return f"{np.mean(v):.{d}f}$\\pm${np.std(v):.{d}f}"


#: Method -> (colour, marker, table column). Every method has its own marker as well as its
#: colour, so the figure reads without colour. GENOT-Q with the Euclidean cost and the models
#: trained on the same cells are in the table only.
FIG_METHODS = {"NGMA": ("#2a78d6", "o", "NGMA"),
               "NGMA, Euclidean": ("#eda100", "D", "NGMA, Euclidean"),
               "Rosetta": ("#b42318", "s", "Rosetta"),
               "mini-vec2vec": ("#6b21a8", "v", "mini-vec2vec"),
               "GENOT-Q": ("#1a7f37", "^", "GENOT-Q, pullback cost"),
               "RelGeo (labels)": ("#be185d", "P", "RelGeo$^\\dagger$")}

#: The panels: (measure, y label, y scale, y limits, has a map ceiling).
PANELS = {"r1": ("R@1", "linear", (0, 0.75), True),
          "type": ("cell-type accuracy", "linear", (0, 1.0), True)}


def _panel(ax, acc, metric, letter, chance_type, kind):
    ylabel, yscale, ylim, has_map = PANELS[metric]
    xs = np.array(SIZES, float)
    offs = np.linspace(-0.07, 0.07, len(FIG_METHODS))
    ceil = (("map", "#525252"), ("Procrustes", "#a3a3a3"))
    ax.grid(axis="y", color="#ececec", linewidth=0.6, which="major")
    ax.set_axisbelow(True)
    for col, color in ceil:
        if col == "map" and not has_map:
            continue
        mu = [np.mean([x for x in acc[col](sz, kind, metric) if x is not None] or [np.nan]) for sz in SIZES]
        if np.all(np.isnan(mu)):
            continue
        ax.plot(xs, mu, color=color, linestyle="--", linewidth=0.9, zorder=1)
    if metric == "type":
        ax.axhline(chance_type, color="#d4d4d4", linestyle=":", linewidth=0.8, zorder=1)
        ax.text(xs[0] * 0.86, chance_type + 0.02, "chance", fontsize=6, color="#a3a3a3")
    for (name, (color, mk, col)), off in zip(FIG_METHODS.items(), offs):
        vals = [[x for x in acc[col](sz, kind, metric) if x is not None] for sz in SIZES]
        if not any(vals):
            continue                                   # not recorded for this measure
        x = xs * np.exp(off)
        for xi, v in zip(x, vals):                     # the draws behind each mean
            ax.scatter(np.full(len(v), xi), v, s=5, color=color, alpha=0.3, linewidths=0, zorder=2)
        mu = [np.mean(v) for v in vals]
        main = name == "NGMA"
        ax.plot(x, mu, color=color, marker=mk, markersize=4.6 if main else 3.6,
                linewidth=1.6 if main else 0.9, markeredgecolor="white", markeredgewidth=0.4,
                zorder=4 if main else 3)
    ax.set_xscale("log")
    ax.set_yscale(yscale)
    ax.set_xticks(xs)
    ax.set_xticklabels([f"{int(x):,}" for x in xs])
    ax.minorticks_off()
    ax.set_xlim(xs[0] * 0.78, xs[-1] * 1.3)
    ax.set_ylim(*ylim)
    ax.set_xlabel("training cells per model", fontsize=7)
    ax.set_ylabel(ylabel, fontsize=7)
    ax.tick_params(labelsize=6.5)
    ax.set_title(f"({letter})", loc="left", fontsize=7.5, fontweight="bold")


def figure(acc, out, chance_type, kind="cross"):
    """fig_lung_main, 1 x 2: R@1 and cell-type accuracy of the models trained on different cells
    against training size. Lines join the means over 2 pairings x 3 draws; faint markers are the
    six draws; grey dashed lines are the maps fitted on the true pairs."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    from tueplots import bundles
    plt.rcParams.update(bundles.neurips2024(usetex=False, ncols=2, nrows=1, family="serif"))
    plt.rcParams.update({"axes.spines.top": False, "axes.spines.right": False})
    handles = [Line2D([], [], color=c, marker=mk, markersize=3.8, markeredgecolor="white",
                      markeredgewidth=0.4, linewidth=1.6 if n == "NGMA" else 0.9, label=n)
               for n, (c, mk, _) in FIG_METHODS.items()]
    handles += [Line2D([], [], color=c, linestyle="--", linewidth=0.9, label=lab)
                for lab, c in (("map, true pairs", "#525252"), ("Procrustes, true pairs", "#a3a3a3"))]
    caption = ("scVI models of Tabula Sapiens lung cells trained on different cells: (a) retrieval of the true partner "
               "among $10{,}000$ held-out cells (R@1, chance $10^{-4}$) and (b) cell-type accuracy of the nearest "
               "cell, on disjoint samples of $3000$ cells per side, against the number of training cells "
               "per model. NGMA is scored by the combined ranking of both maps. Lines join means over two model "
               "pairings and three draws; faint markers are the six draws. Grey dashed lines are not methods: the "
               "same map class and the orthogonal (Procrustes) map fitted on the true pairs. GENOT-Q uses the "
               "pullback cost; its Euclidean-cost variant and the models trained on the same cells are in "
               "Table~\\ref{tab:lung_baselines}. RelGeo builds its anchors from the cell-type labels.")
    name = "fig_lung_main"
    fig, axes = plt.subplots(1, 2, figsize=(5.5, 1.75), squeeze=False)
    for j, (metric, letter) in enumerate((("r1", "a"), ("type", "b"))):
        _panel(axes[0][j], acc, metric, letter, chance_type, kind)
    fig.legend(handles=handles, loc="center right", ncol=1, frameon=False, fontsize=6.0,
               bbox_to_anchor=(1.0, 0.5), handlelength=1.8)
    fig.tight_layout(rect=(0, 0, 0.78, 1))
    for ext in ("pdf", "png"):
        fig.savefig(out / f"{name}.{ext}", bbox_inches="tight", dpi=300 if ext == "png" else None)
    (out / f"{name}.tex").write_text(
        HEADER.format(src="results/lung_table.csv and baselines/lung_baselines.csv")
        + "\\begin{figure}[t]\n  \\centering\n  \\includegraphics[width=\\textwidth]{figures/" + name + ".pdf}\n"
        "  \\caption{" + caption + "}\n  \\label{fig:lung_main}\n\\end{figure}\n")
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True, help="the experiment's root directory")
    ap.add_argument("--out", default=None, help="output directory (default <root>/tables)")
    a = ap.parse_args()
    root = Path(a.root)
    out = Path(a.out) if a.out else root / "tables"
    out.mkdir(parents=True, exist_ok=True)
    allrows = list(csv.DictReader(open(root / "results" / "lung_table.csv")))
    lt = [r for r in allrows if r["regime"] == "disjoint"]
    bl = list(csv.DictReader(open(root / "baselines" / "lung_baselines.csv")))
    ngma = defaultdict(dict)                      # (size, kind, M) -> column -> list over pairs x draws
    for r in lt:
        for k, v in r.items():
            ngma[(int(r["size"]), r["kind"], r["M"])].setdefault(k, []).append(num(v) if k not in ("pair", "kind", "M", "regime") else v)
    base = defaultdict(lambda: defaultdict(list))  # (size, kind, method) -> {"r1": [...], "type": [...]}
    per_carve = defaultdict(dict)
    for r in bl:
        kind = "cross" if r["pair"].startswith("cross") else "within"
        key = (int(r["size"]), kind, r["method"])
        base[key]["r1"].append(num(r["r1_ab"]))
        base[key]["type"].append(num(r["type_acc_ab"]))
        base[key]["csls"].append(num(r.get("csls_ab")))
        base[key]["fos"].append(num(r.get("foscttm_ab")))
        per_carve[(int(r["size"]), r["pair"], int(r["draw"]))][r["method"]] = num(r["r1_ab"])
    chance_type = np.mean([x for x in ngma[(4900, "cross", "8")]["chance_type_acc"] if x is not None])
    for r in lt:
        if r["M"] == "8":
            key = (int(r["size"]), r["pair"], int(r["draw"]))
            if key in per_carve:
                per_carve[key]["NGMA"] = num(r["r1"])

    # --- tab_lung_baselines.tex: NGMA against the baselines ------------------------------------
    NG = {"r1": "r1", "type": "type_acc", "fos": "foscttm"}   # the combined ranking; no combined CSLS
    MAPC = {"r1": "ceil_map_r1_ab", "type": "ceil_map_type_ab"}
    PROC = {"r1": "ceil_proc_r1_ab", "type": "ceil_proc_type_ab", "csls": "ceil_proc_csls_at1_ab",
            "fos": "ceil_proc_foscttm_ab"}
    cols = [("NGMA", lambda s, k, m: ngma[(s, k, "8")].get(NG[m], []) if m in NG else []),
            ("NGMA, Euclidean", lambda s, k, m: ngma[(s, k, "euc")].get(NG[m], []) if m in NG else []),
            ("NGMA, one decoder", lambda s, k, m: ngma[(s, k, "1")].get(NG[m], []) if m in NG else []),
            ("Rosetta", lambda s, k, m: base[(s, k, "Rosetta")][m]),
            ("mini-vec2vec", lambda s, k, m: base[(s, k, "mini-vec2vec")][m]),
            ("GENOT-Q, Eucl.\\ cost", lambda s, k, m: base[(s, k, "GENOT-Q euc")][m]),
            ("GENOT-Q, pullback cost", lambda s, k, m: base[(s, k, "GENOT-Q pullback")][m]),
            ("RelGeo$^\\dagger$", lambda s, k, m: base[(s, k, "RelGeo")][m]),
            ("map", lambda s, k, m: ngma[(s, k, "8")].get(MAPC[m], []) if m in MAPC else []),
            ("Procrustes", lambda s, k, m: ngma[(s, k, "8")].get(PROC[m], []))]
    L = [HEADER.format(src="results/lung_table.csv and baselines/lung_baselines.csv"),
         "\\begin{table}[t]\n\\centering\n",
         "\\caption{scVI models of Tabula Sapiens lung cells (Appendix~\\ref{app:lung}): NGMA against the unpaired "
         "baselines, on the disjoint samples ($n=3000$ cells per side) of two models trained on different "
         "cells or on the same cells with different seeds, by training size. Retrieval of the true partner "
         "among the $10{,}000$ evaluation cells (R@1, chance $10^{-4}$) and cell-type accuracy of the nearest "
         "cell (chance " + f"{chance_type:.3f}" + "), scored as in Table~\\ref{tab:alignment}. GENOT-Q runs on its "
         "own GW coupling with the Euclidean cost or with the pullback cost NGMA uses. NGMA, one decoder, reads "
         "the pullback metric of the scVI decoder alone instead of the ensemble of eight. The last two columns "
         "are not methods. They are NGMA's map class and the orthogonal map, both fitted on the true pairs "
         "and scored $a \\to b$. Mean $\\pm$ s.d.\\ over two pairings and three draws. "
         "$^\\dagger$RelGeo builds its anchors from the cell-type labels of both models.}\n"
         "\\label{tab:lung_baselines}\n\\vspace{4pt}\n\\scriptsize\n\\resizebox{\\textwidth}{!}{%\n"
         "\\begin{tabular}{ll" + "c" * len(cols) + "}\n\\toprule\n",
         " & & NGMA & NGMA, Euclidean & NGMA, one decoder & Rosetta & mini-vec2vec & GENOT-Q, Eucl.\\ cost "
         "& GENOT-Q, pullback cost & RelGeo$^\\dagger$ & \\multicolumn{2}{c}{fitted on true pairs} \\\\\n"
         "\\cmidrule(lr){11-12}\n",
         "Cells & training size &  &  &  &  &  &  &  &  & map & Procrustes \\\\\n\\midrule\n"]
    blocks = (("r1", "R@1"), ("type", "cell-type accuracy"))
    for bi, (m, title) in enumerate(blocks):
        L.append(f"\\multicolumn{{{len(cols) + 2}}}{{l}}{{\\emph{{{title}}}}} \\\\\n")
        for kind, kname in KINDS:
            for s in SIZES:
                L.append(f"{kname} & {s:,} & " + " & ".join(ms(f(s, kind, m)) for _, f in cols) + " \\\\\n")
        L.append("\\midrule\n" if bi < len(blocks) - 1 else "")
    L.append("\\bottomrule\n\\end{tabular}\n}\n\\end{table}\n")
    (out / "tab_lung_baselines.tex").write_text("".join(L))

    # --- tab_lung_resolution.tex: resolution and the ensemble ----------------------------------
    L = [HEADER.format(src="results/lung_table.csv"),
         "\\begin{table}[t]\n\\centering\n",
         "\\caption{scVI lung models: what NGMA recovers, by training size. R@1 of NGMA's combined ranking "
         "(both directions) with one decoder ($M=1$), the eight-decoder ensemble ($M=8$) and Euclidean "
         "geometry; at $M=8$, R@1 with candidates restricted to the cell's own type (chance: the mean of "
         "1/(cells of that type), " + f"{np.mean([x for x in ngma[(4900, 'cross', '8')]['chance_type'] if x is not None]):.4f}"
         + "), and the cell-type and compartment accuracy of the nearest cell (chance "
         + f"{chance_type:.3f}" + " and " + f"{np.mean([x for x in ngma[(4900, 'cross', '8')]['chance_comp_acc'] if x is not None]):.3f}"
         + "). Disjoint samples, mean $\\pm$ s.d.\\ over two pairings and three draws.}\n"
         "\\label{tab:lung_resolution}\n\\vspace{4pt}\n\\scriptsize\n\\resizebox{\\textwidth}{!}{%\n\\begin{tabular}{llcccccc}\n\\toprule\n"
         " & & \\multicolumn{3}{c}{R@1} & \\multicolumn{3}{c}{$M=8$} \\\\\n\\cmidrule(lr){3-5} \\cmidrule(lr){6-8}\n"
         "Cells & training size & $M=1$ & $M=8$ & Euclidean & R@1 within type & cell type & compartment \\\\\n\\midrule\n"]
    for kind, kname in KINDS:
        for s in SIZES:
            g = lambda M, c: ngma[(s, kind, M)].get(c, [])
            L.append(f"{kname} & {s:,} & {ms(g('1', 'r1'))} & {ms(g('8', 'r1'))} & {ms(g('euc', 'r1'))} & "
                     f"{ms(g('8', 'r1_type'))} & {ms(g('8', 'type_acc'))} & {ms(g('8', 'comp_acc'))} \\\\\n")
    L.append("\\bottomrule\n\\end{tabular}\n}\n\\end{table}\n")
    (out / "tab_lung_resolution.tex").write_text("".join(L))

    # --- tab_lung_draws.tex: every carve ------------------------------------------------------
    meths = ["NGMA", "Rosetta", "mini-vec2vec", "GENOT-Q euc", "GENOT-Q pullback", "RelGeo", "Procrustes ceiling"]
    L = [HEADER.format(src="baselines/lung_baselines.csv"),
         "\\begin{table}[t]\n\\centering\n\\caption{scVI lung models, every sample: R@1 $a\\to b$ on the disjoint "
         "samples. Pairs 1 and 2 are trained on different cells (the two training halves, one pair per seed), "
         "pairs 3 and 4 on the same cells with different seeds; draws 1--3 are independent disjoint samples. "
         "The last column is not a method: Procrustes fitted on the true pairs.}\n\\label{tab:lung_draws}\n\\vspace{4pt}\n"
         "\\scriptsize\n\\resizebox{\\textwidth}{!}{%\n\\begin{tabular}{llc" + "c" * len(meths) + "}\n\\toprule\n",
         "Training size & pair & draw & NGMA & Rosetta & mini-vec2vec & GENOT-Q (Eucl.) & GENOT-Q (pullback) & RelGeo & Procrustes (true pairs) \\\\\n\\midrule\n"]
    for (s, p, d) in sorted(per_carve, key=lambda k: (k[0], PAIR_NO[k[1]], k[2])):
        v = per_carve[(s, p, d)]
        L.append(f"{s:,} & {PAIR_NO[p]} & {d} & " + " & ".join("--" if v.get(m) is None else f"{v[m]:.3f}" for m in meths) + " \\\\\n")
    L.append("\\bottomrule\n\\end{tabular}\n}\n\\end{table}\n")
    (out / "tab_lung_draws.tex").write_text("".join(L))

    # --- the numbers the text quotes -----------------------------------------------------------
    gaps_r1, gaps_t, above_proc = [], [], 0
    for key, v in per_carve.items():
        bm = [m for m in ("Rosetta", "mini-vec2vec", "GENOT-Q euc", "GENOT-Q pullback", "RelGeo") if v.get(m) is not None]
        gaps_r1.append(v["NGMA"] - max(v[m] for m in bm))
        above_proc += v["NGMA"] > v["Procrustes ceiling"]
    tp = defaultdict(dict)
    for r in bl:
        tp[(int(r["size"]), r["pair"], int(r["draw"]))][r["method"]] = num(r["type_acc_ab"])
    for r in lt:
        if r["M"] == "8":
            key = (int(r["size"]), r["pair"], int(r["draw"]))
            if key in tp:
                tp[key]["NGMA"] = num(r["type_acc"])
    for v in tp.values():
        bm = [m for m in ("Rosetta", "mini-vec2vec", "GENOT-Q euc", "GENOT-Q pullback", "RelGeo") if v.get(m) is not None]
        gaps_t.append(v["NGMA"] - max(v[m] for m in bm))
    euc_fail = sum(1 for r in lt if r["M"] == "euc" and r["kind"] == "cross" and num(r["r1"]) is not None and num(r["r1"]) < 0.01)
    euc_n = sum(1 for r in lt if r["M"] == "euc" and r["kind"] == "cross")
    nums = {"n_carves": len(per_carve), "gap_r1_min": min(gaps_r1), "gap_r1_max": max(gaps_r1),
            "gap_type_min": min(gaps_t), "gap_type_max": max(gaps_t), "ngma_above_procrustes": above_proc,
            "euclidean_cross_draws_below_0.01": f"{euc_fail}/{euc_n}",
            "ngma_m8_minus_m1_cross_min": min(np.mean(ngma[(s, 'cross', '8')]['r1']) - np.mean(ngma[(s, 'cross', '1')]['r1']) for s in SIZES),
            "frac_of_map_ceiling_cross": {s: float(np.mean(ngma[(s, 'cross', '8')]['r1'])
                                                   / np.mean([x for x in ngma[(s, 'cross', '8')][MAPC['r1']] if x is not None]))
                                          for s in SIZES},
            "ngma_r1_cross": {s: float(np.mean(ngma[(s, 'cross', '8')]['r1'])) for s in SIZES},
            "ngma_type_cross": {s: float(np.mean(ngma[(s, 'cross', '8')]['type_acc'])) for s in SIZES},
            "map_ceiling_r1_cross": {s: float(np.mean([x for x in ngma[(s, 'cross', '8')][MAPC['r1']] if x is not None])) for s in SIZES}}

    def mean_of(kind, size, M, regime, col):
        v = [num(r.get(col)) for r in allrows if r["kind"] == kind and int(r["size"]) == size and r["M"] == M
             and r["regime"] == regime and num(r.get(col)) is not None]
        return float(np.mean(v)) if v else None
    nums["r1_combined_cross_disjoint"] = {s: mean_of("cross", s, "8", "disjoint", "r1") for s in SIZES}
    nums["r1_combined_cross_frac100"] = {s: mean_of("cross", s, "8", "frac100", "r1") for s in SIZES}
    nums["foscttm_ab_cross_disjoint_M8"] = {s: mean_of("cross", s, "8", "disjoint", "foscttm_ab") for s in SIZES}
    nums["foscttm_ab_cross_disjoint_euc"] = {s: mean_of("cross", s, "euc", "disjoint", "foscttm_ab") for s in SIZES}
    nums["foscttm_procrustes_cross_ab"] = {s: mean_of("cross", s, "8", "disjoint", "ceil_proc_foscttm_ab") for s in SIZES}
    for meas in ("csls", "fos"):
        for kind in ("cross", "within"):
            nums[f"{meas}_{kind}_by_method"] = {
                name: [None if not [x for x in f(s, kind, meas) if x is not None]
                       else round(float(np.mean([x for x in f(s, kind, meas) if x is not None])), 4) for s in SIZES]
                for name, f in cols}
    json.dump(nums, open(out / "lung_numbers.json", "w"), indent=1)
    figure(dict(cols), out, chance_type)
    print(json.dumps(nums, indent=1))
    print(f"tables in {out}")


if __name__ == "__main__":
    main()
